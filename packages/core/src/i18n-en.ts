function ordinal(n: number): string {
  const s = new Intl.PluralRules('en', { type: 'ordinal' }).select(n);
  return `${n}${({ one: 'st', two: 'nd', few: 'rd' } as Record<string, string>)[s] ?? 'th'}`;
}
