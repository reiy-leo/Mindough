/**
 * 把一个语言标签（zh-TW、pt-PT、en_US、?lang=pt…）对到介绍页的九种之一，对不上返回 null。
 * 页面脚本里直接用这个函数的源码（toString），所以函数里不能引用外面的变量。
 */
export function matchLang(tag: unknown): LandingLang | null {
  const l = String(tag == null ? '' : tag).trim().toLowerCase().replace('_', '-');
  const base = l.split('-')[0];
  if (!base) return null;
  if (base === 'zh') return 'zh';
  if (base === 'pt') return 'pt-BR';
  if (base === 'in') return 'id'; // 印尼语的旧代码
  const plain = ['en', 'es', 'ru', 'ja', 'de', 'fr', 'id'];
  return plain.indexOf(base) >= 0 ? (base as LandingLang) : null;
}

